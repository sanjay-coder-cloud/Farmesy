// Fallback high-quality agricultural photo (verified 200 OK)
export const DEFAULT_CROP_IMAGE = 'https://images.unsplash.com/photo-1574943320219-553eb213f72d?w=700&q=80';

export function getCropImage(cropName: string): string {
  if (CROP_IMAGES[cropName]) return CROP_IMAGES[cropName];
  // Check partial key match
  const lower = cropName.toLowerCase();
  for (const [key, url] of Object.entries(CROP_IMAGES)) {
    if (lower.includes(key.toLowerCase()) || key.toLowerCase().includes(lower)) {
      return url;
    }
  }
  return DEFAULT_CROP_IMAGE;
}

